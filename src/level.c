static const uint8_t (*active_map)[MAP_COLS] = (const uint8_t (*)[MAP_COLS])0;

void level_load(uint8_t n)
{
    if (n >= NUM_LEVELS) n = 0;
    active_map     = level_maps[n];
    level_path     = level_paths[n];
    level_path_len = level_path_lens[n];
    level_waves    = level_wave_tables[n];
}

uint8_t level_cell(uint8_t col, uint8_t row)
{
    if (row >= MAP_ROWS || col >= MAP_COLS) return CELL_WALL;
    return active_map[row][col];
}

void level_init(void)
{
    level_load(0);
}
